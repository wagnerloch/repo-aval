// retorna o valor da soma entre os dois parâmetros
function sum(v1, v2) {
  return v1 + v2;
}

// retorna o valor da subtração entre os dois parâmetros
function sub(v1, v2) {
    return v1 - v2;
}
console.log(sum(5, 3));
console.log(sub(5, 3));

function mult(v1, v2) {
  return v1 * v2;
}

console.log("Multiplicação:", mult(2, 3)); // 6

function div(v1, v2) {
    return v1 / v2;
}

console.log("Divisão:", div(10, 2)); // 5

function square(v1) {
  return Math.sqrt(v1);
}

